"""Renders MODEL_CARD.md from the numbers of a training run. Nothing in here is hand written results."""

from __future__ import annotations

import numpy as np

from .config import DAY, DS_SYNTHETIC, SOURCE_LABEL, TRACK_LABEL, Params, feature_fingerprint
from .dataset import Dataset
from .model import HEAD_KEYS, WHALE_SCALE
from .timeutil import iso
from .track_record import TrackRecordResult
from .training import TrainResult


def _f(x, nd: int = 3) -> str:
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def _d(ts) -> str:
    return "n/a" if ts is None else iso(ts)[:10]


def render_model_card(ds: Dataset, params: Params, tr: TrainResult, track: TrackRecordResult, source: str, now: float) -> str:
    b = tr.bundle
    m = b.metrics
    sp = tr.split
    head = b.head
    demo = SOURCE_LABEL[source] == DS_SYNTHETIC
    total_w = float(head.w.sum() + head.w_gnn)
    caps = head.row_caps()
    ci = m.get("test_auc_ci95")
    lines: list[str] = []
    add = lines.append

    add("# Groundgraph scorer: model card")
    add("")
    add(f"Generated: {iso(now)}  ")
    add(f"Model version: `{b.version}`  ")
    add(f"Data source: `{SOURCE_LABEL[source]}` (track record label `{TRACK_LABEL[source]}`)  ")
    add(f"Parameter fingerprint: `{feature_fingerprint(params)}`, seed {params.seed}")
    add("")
    if demo:
        add("> **These numbers come from DEMO SYNTHETIC data.** The wallets, transfers, trades and prices were generated by")
        add("> `scorer/sources/synthetic.py`, with smart money behaviour planted on purpose. They show that the pipeline")
        add("> works end to end. They are NOT evidence that the model finds smart money on Solana mainnet.")
        add("")
    add("## What the model does")
    add("")
    add("Every wallet gets a score from 0 to 100 that is the sum of five named contributions (whale overlap, entry timing, hit rate,")
    add("centrality, lead time). A two layer GraphSAGE model (mean aggregator, hidden size 64) reads the same five features plus")
    add("degree over the wallet graph. Its cross sectional percentile is folded into the Centrality row, which the UI names")
    add("\"Centrality (graph model)\" (DECISIONS.md, ADR-002). Wallets above a score cut are flagged as smart money, and the")
    add("positioning of flagged wallets in a market becomes a calibrated P(ABOVE) with a confidence interval and an edge versus the")
    add("market price (the radar). The label that the model learns is a PROXY for smart money, not ground truth (see Labels).")
    add("")
    add("## Data window")
    add("")
    add(f"* History: {_d(ds.start_ts)} to {_d(ds.end_ts)} ({(ds.end_ts - ds.start_ts) / DAY:.0f} days)")
    add(f"* Scored wallets: {int(ds.is_wallet.sum())}, graph nodes: {ds.n_nodes}, transfer edges: {ds.e_usd.size}, "
        f"swap trades: {ds.t_ts.size}, virtual markets: {len(ds.markets)}, positions: {ds.positions.n if ds.positions is not None else 0}")
    add(f"* Train cutoffs: {_d(sp.train_cutoffs[0])} to {_d(sp.train_cutoffs[-1])} ({len(sp.train_cutoffs)} snapshots, every "
        f"{params.train_stride_days:.0f} days)")
    add(f"* Embargo: {params.embargo_days:.0f} days between the end of the training labels ({_d(sp.train_end)}) and the first test cutoff ({_d(sp.test_start)})")
    add(f"* Test cutoffs: {_d(sp.test_cutoffs[0])} to {_d(sp.test_cutoffs[-1])} ({len(sp.test_cutoffs)} daily snapshots, "
        f"metrics use every 7th)")
    add(f"* Label tail: a cutoff needs {sp.tail_days:.0f} days (label window {params.label_days:.0f}d plus the longest market "
        f"{params.max_market_days:.0f}d) before its label is final, so no position spans train and test")
    add("")
    add("## Features (point in time, only data before `as_of`)")
    add("")
    add("| Feature | Definition |")
    add("|---|---|")
    add(f"| whale_overlap | share of a wallet's counterparties (30 day window) that are in the top 1% by balance (never fewer than {params.min_whales} whales). Input to the head: min(1, value / {WHALE_SCALE}) |")
    add(f"| entry_timing | share of the wallet's last {params.entry_n} entries (60 day lookback, 24h look-ahead fully elapsed) that came before a {params.move_size * 100:.0f} cent move of the market ABOVE price in its favour. Shrunk towards 0.5 with {params.prior_strength:.0f} pseudo entries |")
    add(f"| hit_rate | share of positions resolved in the trailing 30 days that were on the correct side, leaving out the market being scored. Shrunk towards 0.5 with {params.prior_strength:.0f} pseudo observations |")
    add("| centrality | percentile of weighted PageRank among active wallets, plus the number of communities bridged |")
    add(f"| lead_time_min | median minutes between an early entry and the {params.move_size * 100:.0f} cent move that followed. Input to the head: min(1, minutes / {params.lead_cap_min:.0f}) |")
    add("")
    add("Graph: trailing 30 day window, edge weight = USD with a 7 day half life. GraphSAGE node inputs are the five head inputs, "
        "log degree and an activity flag.")
    add("")
    add("## Labels (smart money proxy)")
    add("")
    add(f"A wallet is labelled positive at cutoff T when, over positions opened in (T, T + {params.label_days:.0f}d], its realised PnL is in the top "
        f"{int(round((1 - params.label_pnl_quantile) * 100))}% of labelled wallets AND at least {int(params.label_early_min * 100)}% of those entries were early "
        f"(followed by a {params.move_size * 100:.0f} cent favourable move within {params.move_horizon_h:.0f}h). Wallets with fewer than "
        f"{params.label_min_events} such positions are unlabelled, never negatives. Train base rate: {_f(m.get('train_base_rate'), 3)} "
        f"({m.get('n_train_positive')} of {m.get('n_train_labeled')} labelled samples). Test base rate: {_f(m.get('test_base_rate'), 3)}.")
    add("")
    add("## Explainable head")
    add("")
    add(f"Monotone linear head, non negative weights (each heuristic weight is at least {params.head_weight_floor}, the graph model share is capped at "
        f"{int(params.gnn_share_cap * 100)}% of the total weight), fitted by class balanced logistic regression on out of fold graph model scores. "
        f"Score = scale x weighted sum, scale = {_f(head.scale, 2)}. Integer points per row use the largest remainder method so they add up to the score exactly.")
    add("")
    add("| Row | Weight share | Max points |")
    add("|---|---|---|")
    shares = list(head.w / total_w) if total_w > 0 else [0] * 5
    shares[3] += head.w_gnn / total_w if total_w > 0 else 0
    names = {"whale_overlap": "Whale overlap", "entry_timing": "Entry timing", "hit_rate": "Hit rate",
             "centrality": "Centrality (graph model)", "lead_time": "Lead time"}
    for k, s in zip(HEAD_KEYS, shares):
        add(f"| {names[k]} | {s * 100:.1f}% | {caps[k]:.1f} |")
    add("")
    add(f"Smart money flag: score >= {_f(head.smart_threshold, 0)} (the cut that maximises F1 on out of fold training predictions among cuts that flag at most {params.max_flag_share * 100:.0f}% of active wallets), plus at least "
        f"{params.min_flag_entries} eligible entries and {params.min_flag_resolved} resolved positions. Top tier: score >= {_f(head.top_threshold, 0)}.")
    add("")
    add("## Held out results (test period, after the embargo)")
    add("")
    add("| Model | ROC AUC | PR AUC |")
    add("|---|---|---|")
    add(f"| Explainable score (deployed) | {_f(m.get('test_auc'))} | {_f(m.get('test_pr_auc'))} |")
    add(f"| Heuristic features only (no graph model) | {_f(m.get('test_auc_heuristic_only'))} | {_f(m.get('test_pr_auc_heuristic_only'))} |")
    add(f"| GraphSAGE logit alone | {_f(m.get('test_auc_graph_model_only'))} | {_f(m.get('test_pr_auc_graph_model_only'))} |")
    add(f"| Hit rate alone | {_f(m.get('test_auc_hit_rate_only'))} | n/a |")
    add(f"| Entry timing alone | {_f(m.get('test_auc_entry_timing_only'))} | n/a |")
    add("")
    add(f"Samples: {m.get('n_test_labeled')} labelled wallet snapshots, {m.get('n_test_positive')} positive, from {m.get('n_test_snapshots')} snapshots. "
        f"The 95% interval of the deployed AUC is {('[' + _f(ci[0]) + ', ' + _f(ci[1]) + ']') if ci else 'n/a'} (bootstrap over funding groups). "
        f"Snapshots of the same wallet are strongly correlated, so the effective sample size is much smaller than the row count. "
        f"Cross validated AUC on the training period (group k-fold by funding cluster, {m.get('cv_folds', 'n/a')} folds): graph model {_f(m.get('cv_auc_graph_model'))}, head {_f(m.get('cv_auc_head'))}. "
        f"PR AUC must be read against the base rate of {_f(m.get('test_base_rate'), 3)}.")
    add("")
    add("## Radar and track record (backtest on VIRTUAL markets)")
    add("")
    add("The Track record page is a backtest on virtual markets built from price history, NOT live Groundgraph markets. "
        "For each virtual market that settled in the test period, the radar is computed from information available 24 hours before settlement "
        "(wallet scores as of the last daily cutoff, positions taken by flagged wallets by then) and compared with the virtual market price "
        "at the same time (fair value digital option with trailing volatility).")
    add("")
    add(f"* Markets with a ready radar: {track.n_markets} (building, skipped: {track.n_building}, total candidates: {track.n_total})")
    add(f"* Brier, radar {_f(track.brier_radar, 4)} versus market {_f(track.brier_market, 4)} (lower is better). Raw uncalibrated radar Brier: {_f(track.extra.get('raw_brier'), 4)}")
    add(f"* Directional hit rate, radar {_f(track.hit_rate_radar, 3)} versus market {_f(track.hit_rate_market, 3)}")
    add(f"* Median lead time from the first flagged entry to a {params.move_size * 100:.0f} cent move: {_f(track.median_lead_min, 0)} min (n={track.extra.get('n_leads', 0)})")
    if track.edge_realized_cents is None:
        add(f"* Realised edge: not reported. Only {track.n_edge_trades} hypothetical positions had a radar edge above {params.edge_threshold_cents:.0f} cents "
            f"(minimum {params.min_edge_trades}), too few for an average to mean anything.")
    else:
        add(f"* Realised edge buying the side with radar edge above {params.edge_threshold_cents:.0f} cents: {_f(track.edge_realized_cents, 2)} cents per share net of an assumed "
            f"{params.assumed_fee_bps / 100:.2f}% fee ({_f(track.edge_realized_gross_cents, 2)} gross), n={track.n_edge_trades}")
    ci = track.extra.get("brier_diff_ci95")
    if ci:
        verdict = "the interval contains zero: no detectable difference from the market" if ci[0] <= 0.0 <= ci[1] else (
            "the radar was closer to the outcome than the market" if ci[1] < 0 else "the radar was further from the outcome than the market")
        add(f"* Brier difference (radar minus market) 95% interval over markets: [{_f(ci[0], 4)}, {_f(ci[1], 4)}], {verdict}.")
    con = track.extra.get("contested") or {}
    if con.get("n"):
        add(f"* Markets still undecided 24h before settlement (market price between 5 and 95 cents): n={con['n']}, Brier radar {_f(con['brier_radar'], 4)} versus market {_f(con['brier_market'], 4)}. "
            f"On the other {track.n_markets - con['n']} markets the price was already near 0 or 1, where no method can add much.")
    add(f"* Expected calibration error (10 equal width bins, weighted mean |predicted - observed|): radar {_f(track.extra.get('ece'), 4)}, market {_f(track.extra.get('ece_market'), 4)}. "
        f"Lower is better; with {track.n_markets} markets and most of them near 0 or 1 this number is dominated by a few bins and is not precise.")
    if track.extra.get("calibration_adopted"):
        add(f"* Calibration: an isotonic regression fitted on {track.calibrator.n} markets is used (cross fitted Brier {_f(track.extra.get('calibrated_oof_brier'), 4)} against "
            f"{_f(track.extra.get('raw_brier'), 4)} raw). Reported numbers are cross fitted (5 folds), so each market is calibrated by a model that never saw it.")
    else:
        add(f"* Calibration: an isotonic regression is only adopted when it lowers the cross fitted Brier score of the raw radar. Here it did not "
            f"(cross fitted {_f(track.extra.get('calibrated_oof_brier'), 4)} against raw {_f(track.extra.get('raw_brier'), 4)}, or fewer than {params.radar_calibration_min} markets), "
            f"so the identity mapping is used and the radar probability is the raw formula output.")
    add("")
    add("## Known failure modes")
    add("")
    add("* Sybil and copy trading: wallets funded by one source that copy a profitable leader look like several independent smart wallets. "
        f"Flagged wallets sharing a non hub funder within {params.sybil_hops} hops (at least {params.sybil_min_wallets}) get their weight capped at x{params.radar_sybil_cap}. Operators that fund through many hops or through exchanges are not caught.")
    add("* Thin markets: the radar needs at least 3 flagged wallets and 10 scored trades, otherwise it shows the Building state. With few flagged wallets the confidence interval is wide and the edge is noise.")
    add("* Regime change: labels come from a recent window. After a volatility regime change the early entry and PnL proxies shift, so the weekly retrain matters.")
    add("* Label proxy: top decile PnL and early entries can reward luck and large size. The model predicts the proxy, not skill.")
    add("* Short history: with few weeks of data the temporal split leaves only a handful of train snapshots and the metrics have wide intervals.")
    add("* Wallet identity: one person can use many wallets and one wallet can be shared. Funding source is the only link used.")
    add("* Funding source on Helius data is the first inbound SOL transfer found inside the backfill window, so it can be a later funder for old wallets.")
    add("")
    add("## Limitations")
    add("")
    add("* Wallet behaviour is spot swapping of allow-listed assets mapped to virtual markets (a buy is an ABOVE position, a sell is a BELOW position). It is not a record of trading on Groundgraph markets.")
    add("* Virtual market prices are model fair values, not traded prices, so the radar versus market comparison measures information beyond a volatility model, not beyond a liquid market.")
    add("* Position sizes in the backtest come from swap USD amounts, not from pool positions.")
    add("* Scores describe on-chain behaviour only. They are not advice, and the label can be hidden by the wallet owner.")
    add("* The graph model adds capacity but only a capped share of the displayed score, so a wallet's score is explained mostly by the four heuristics.")
    add("")
    add("## How demo-synthetic data differs from real data")
    add("")
    add("* Informed wallets are planted: they trade a few minutes to hours before permanent price jumps and lean towards the 21 day return with a fixed accuracy. Real smart money is rarer, noisier and not stationary.")
    add("* Clusters are drawn from six behaviour profiles with different trade rates, sizes and linking habits. Louvain recovers them easily. Real graphs are far messier.")
    add("* Whales, exchange like hubs and three sybil operators are planted with simple rules. Real funding paths are longer and noisier.")
    add("* Prices are a random walk with jumps, with no microstructure, no correlation between assets and no news.")
    add("* Every record carries `data_source = 'demo-synthetic'`, the API only serves it when DEMO_MODE=true, and the UI must label it Demo data.")
    add("* AUC on this data mostly shows how well the model recovers the planted structure. Expect real mainnet numbers to be lower.")
    add("")
    add("## Reproducibility")
    add("")
    add(f"Seeded numpy and torch (seed {params.seed}), single thread torch, deterministic algorithms, sorted iteration everywhere. "
        "Re-running with the same data and parameters gives identical weights (tests/test_pipeline.py::test_training_is_deterministic_in_process and ::test_training_is_deterministic_across_processes_and_hash_seeds).")
    add("")
    return "\n".join(lines)
